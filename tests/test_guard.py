class TestGeneratedTreeViolation(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)

    def tearDown(self):
        self._tmp.cleanup()

    def test_claude_memory_is_hand_edited_not_generated(self):
        """`.claude/memory/` is Claude Code's own auto-memory directory — hand/session-maintained,
        never regenerated by a plugin, regardless of which filename lives under it."""
        self.assertIsNone(
            g.generated_tree_violation(".claude/memory/MEMORY.md", self.root)
        )
        self.assertIsNone(
            g.generated_tree_violation(".claude/memory/project_foo.md", self.root)
        )

    def test_other_claude_paths_still_flagged_as_generated(self):
        self.assertIsNotNone(
            g.generated_tree_violation(".claude/plugins/cache/x.json", self.root)
        )


class TestBoardDirCarveOut(unittest.TestCase):
    """Board card + agent-log dirs stay writable from any session root; a
    write that is out of scope AND in no git repo asks instead of a silent deny."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.base = Path(self._tmp.name).resolve()
        self.ws = self.base / "ws"
        (self.ws / "_KANBAN" / "CHANTIER0025" / "3-in-progress").mkdir(parents=True)
        self.session_root = self.base / "repo"
        self.session_root.mkdir()

    def tearDown(self):
        self._tmp.cleanup()

    def _env(self):
        return unittest.mock.patch.dict(
            os.environ,
            {
                "KANBAN_ROOTS": str(self.ws),
                "CLAUDE_PROJECT_DIR": str(self.session_root),
            },
        )

    def _decide(self, target, root=None):
        root = root or self.session_root
        event = {
            "tool_name": "Write",
            "tool_input": {"file_path": str(target)},
            "cwd": str(root),
        }
        return g.decide(event, root)

    def test_card_write_allowed_from_a_foreign_session_root(self):
        card = self.ws / "_KANBAN" / "CHANTIER0025" / "3-in-progress" / "x.md"
        with self._env():
            self.assertIsNone(self._decide(card))

    def test_agent_log_write_allowed_before_the_dir_exists(self):
        entry = (
            self.ws / "_KANBAN" / "_AGENT_LOG" / "2026-09-09_claude.md"
        )  # _AGENT_LOG not created
        with self._env():
            self.assertIsNone(self._decide(entry))

    def test_out_of_scope_non_repo_target_asks(self):
        target = self.base / "elsewhere" / "config.toml"
        target.parent.mkdir()
        with self._env():
            decision = self._decide(target)
        self.assertEqual(decision["hookSpecificOutput"]["permissionDecision"], "ask")

    def test_out_of_scope_other_repo_target_denies(self):
        other = self.base / "otherrepo"
        other.mkdir()
        subprocess.run(["git", "init", "-q", str(other)], check=True)
        with self._env():
            decision = self._decide(other / "app.py")
        self.assertEqual(decision["hookSpecificOutput"]["permissionDecision"], "deny")

    def test_board_resolution_failure_degrades_to_ask_not_deny(self):
        other = self.base / "otherrepo"
        other.mkdir()
        subprocess.run(["git", "init", "-q", str(other)], check=True)
        with unittest.mock.patch.object(
            g, "board_dirs", return_value=g.BoardDirs([], False)
        ):
            decision = self._decide(other / "app.py")
        self.assertEqual(decision["hookSpecificOutput"]["permissionDecision"], "ask")

    def test_freeze_does_not_block_a_board_card_under_the_session_root(self):
        g.save_state(
            g.state_path(self.ws),
            {"careful": False, "freeze": [str(self.ws / "src")], "deny": []},
        )
        card = self.ws / "_KANBAN" / "CHANTIER0025" / "3-in-progress" / "x.md"
        with unittest.mock.patch.dict(
            os.environ,
            {"KANBAN_ROOTS": str(self.ws), "CLAUDE_PROJECT_DIR": str(self.ws)},
        ):
            self.assertIsNone(self._decide(card, root=self.ws))


class TestIsSessionScratchpad(unittest.TestCase):
    """`is_session_scratchpad` recognizes the harness's own path shape, independent of which
    temp root it sits under — `tempfile.gettempdir()` follows macOS's per-user `$TMPDIR`
    (`/var/folders/.../T`), which is NOT where the harness actually writes (`/private/tmp`)."""

    def test_matches_the_real_shape_under_private_tmp(self):
        self.assertTrue(
            g.is_session_scratchpad(
                "/private/tmp/claude-501/-Users-x-repo/session-id/scratchpad/out.txt"
            )
        )

    def test_matches_under_an_unrelated_temp_root_too(self):
        """The check is shape-based, not anchored to `/private/tmp` specifically."""
        self.assertTrue(
            g.is_session_scratchpad(
                "/var/folders/tz/xyz/T/claude-501/-Users-x-repo/session-id/scratchpad/out.txt"
            )
        )

    def test_repo_file_is_not_a_scratchpad(self):
        self.assertFalse(g.is_session_scratchpad("/Users/x/repo/README.md"))

    def test_claude_numbered_dir_without_a_scratchpad_segment_does_not_match(self):
        self.assertFalse(g.is_session_scratchpad("/Users/x/claude-501/notes.txt"))

    def test_scratchpad_segment_before_the_claude_dir_does_not_match(self):
        """`scratchpad` must come AFTER the `claude-<uid>` segment, not before it."""
        self.assertFalse(
            g.is_session_scratchpad("/Users/x/scratchpad/claude-501/out.txt")
        )


class TestScratchpadCarveOut(unittest.TestCase):
    """The session's own scratchpad is always writable — same treatment as board dirs — because
    a `context: fork` skill writing there has no channel back to answer an interactive `ask`."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.base = Path(self._tmp.name).resolve()
        self.session_root = self.base / "repo"
        self.session_root.mkdir()
        self.scratchpad = self.base / "claude-999" / "sess" / "scratchpad"
        self.scratchpad.mkdir(parents=True)

    def tearDown(self):
        self._tmp.cleanup()

    def _decide(self, target):
        event = {
            "tool_name": "Write",
            "tool_input": {"file_path": str(target)},
            "cwd": str(self.session_root),
        }
        with unittest.mock.patch.object(
            g, "board_dirs", return_value=g.BoardDirs([], True)
        ):
            return g.decide(event, self.session_root)

    def test_scratchpad_write_is_allowed_outside_any_repo(self):
        target = self.scratchpad / "commit_messages.txt"
        with unittest.mock.patch.dict(
            os.environ, {"CLAUDE_PROJECT_DIR": str(self.session_root)}
        ):
            self.assertIsNone(self._decide(target))

    def test_freeze_does_not_block_the_scratchpad(self):
        g.save_state(
            g.state_path(self.session_root),
            {"careful": False, "freeze": [str(self.session_root)], "deny": []},
        )
        target = self.scratchpad / "commit_messages.txt"
        with unittest.mock.patch.dict(
            os.environ, {"CLAUDE_PROJECT_DIR": str(self.session_root)}
        ):
            self.assertIsNone(self._decide(target))


if __name__ == "__main__":
    unittest.main()
