    def test_large_command_is_analysed_in_under_a_second(self):
        block = (
            "cat <<'EOF' > out.txt\n"
            + ('it\'s "quoted" /x /y text\n' * 20)
            + "EOF\n"
            + "git commit -m \"a /clear b\" && echo 'c /add-dir d' >> log.txt\n"
        )
